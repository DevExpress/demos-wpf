    public class SelectedItemNameBindingBehavior : Behavior<TreeMapControl> {
        public static readonly DependencyProperty SelectedItemNameProperty = DependencyProperty.Register(nameof(SelectedItemName), typeof(string),
            typeof(SelectedItemNameBindingBehavior), new PropertyMetadata(null, (d, e) => ((SelectedItemNameBindingBehavior)d).OnSelectedItemNameChanged()));
        public static readonly DependencyProperty CountriesInfoProperty =
            DependencyProperty.Register(nameof(CountriesInfo), typeof(CountriesInfo), typeof(SelectedItemNameBindingBehavior), new PropertyMetadata(null));

        public string SelectedItemName {
            get { return (string)GetValue(SelectedItemNameProperty); }
            set { SetValue(SelectedItemNameProperty, value); }
        }
        public CountriesInfo CountriesInfo {
            get { return (CountriesInfo)GetValue(CountriesInfoProperty); }
            set { SetValue(CountriesInfoProperty, value); }
        }

        void TreeMapSelectionChanged(object sender, TreeMapSelectionChangedEventArgs e) {
            var info = (CountryStatisticInfo)e.Selection.FirstOrDefault();
            if (info != null)
                SelectedItemName = info.Name;
        }
        void OnSelectedItemNameChanged() {
            if (AssociatedObject != null)
                AssociatedObject.SelectedItem = CountriesInfo.SingleOrDefault(info => info.Name == SelectedItemName);
        }

        protected override void OnAttached() {
            base.OnAttached();
            AssociatedObject.SelectionChanged += TreeMapSelectionChanged;
            OnSelectedItemNameChanged();
        }
    }

    class ChartPaletteToTreeMapPaletteConverter : ForwardOnlyValueConverter {
        public override object Convert(object value, Type targetType, object parameter, CultureInfo culture) {
            Palette chartColors = (Palette)value;
            DoubleCollection rangeStops = (DoubleCollection)parameter;
            int colorsCount = (int)(rangeStops[rangeStops.Count - 1] - rangeStops[0]) + 1;

            DevExpress.Xpf.TreeMap.CustomPalette palette = new DevExpress.Xpf.TreeMap.CustomPalette();
            for (int i = 0; i < colorsCount; i++)
                palette.Colors.Add(chartColors[i]);
            return palette;
        }
    }

    class SelectedIndexToBrushConverter : MarkupExtension, IMultiValueConverter {
        public object Convert(object[] values, Type targetType, object parameter, CultureInfo culture) {
            if (values[0].GetType() != typeof(int) || (int)values[0] < 0 || !(values[1] is Palette))
                return null;
            int index = (int)values[0];
            Palette palette = (Palette)values[1];
            SolidColorBrush brush = new SolidColorBrush(palette[index]);
            brush.Freeze();
            return brush;
        }
        public object[] ConvertBack(object value, Type[] targetTypes, object parameter, CultureInfo culture) {
            return null;
        }
        public override object ProvideValue(IServiceProvider serviceProvider) {
            return this;
        }
    }
