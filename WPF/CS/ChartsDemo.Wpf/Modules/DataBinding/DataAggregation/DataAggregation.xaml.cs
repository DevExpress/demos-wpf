    public partial class DataAggregationDemo : ChartsDemoModule {
        public DataAggregationDemo() {
            ModuleLoaded += OnModuleLoaded;
            InitializeComponent();
        }
        void OnTabControlSelectionChanged(object sender, TabControlSelectionChangedEventArgs e) {
            UpdateTabContent();
        }
        void OnModuleLoaded(object sender, RoutedEventArgs e) {
            UpdateTabContent();
        }
        void UpdateTabContent() {
            if (!IsModuleLoaded)
                return;
            var selectedTab = tabControl.SelectedContainer;
            if (selectedTab == null || selectedTab.Content != null)
                return;
            if (selectedTab == numericTab) {
                LoadTabContent(selectedTab, () => new NumericDataAggregationTab());
                return;
            }
            if (selectedTab == dateTimeTab) {
                LoadTabContent(selectedTab, () => new DateTimeDataAggregationTab());
                return;
            }
            if (selectedTab == qualitative) {
                LoadTabContent(selectedTab, () => new QualitativeDataAggregationTab());
                return;
            }
            if (selectedTab == timeSpan) {
                LoadTabContent(selectedTab, () => new TimeSpanDataAggregationTab());
                return;
            }
        }
        void LoadTabContent(DXTabItem tab, Func<FrameworkElement> createContent) {
            MainWindow.Instance.ShowSplashScreen();
            var content = createContent();
            content.Loaded += OnTabContentLoaded;
            tab.Content = content;
        }
        void OnTabContentLoaded(object sender, RoutedEventArgs e) {
            FrameworkElement content = (FrameworkElement)sender;
            content.Loaded -= OnTabContentLoaded;
            Dispatcher.InvokeAsync(() => { MainWindow.Instance.HideSplashScreen(); }, DispatcherPriority.ContextIdle);
        }
    }
}
