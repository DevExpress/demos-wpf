using DevExpress.Xpf.Core;
using DevExpress.Xpf.DemoBase;

namespace SchedulingDemo {
    [NoAutogeneratedCodeFiles, CodeFiles(
        "Modules/Highlighted/PrintingTemplatesDemoModule.xaml",
        "ViewModels/Highlighted/PrintingTemplatesDemoViewModel.(cs)",
        "Themes/Ribbon.xaml")]
    public partial class PrintingTemplatesDemoModule : SchedulingDemoModule {
        bool IsModuleLoaded { get; set; }
        public PrintingTemplatesDemoModule() {
            InitializeComponent();
            MainWindow.CommonRibbon.Init(scheduler);
            MainWindow.CommonRibbon.ShowPageHome = false;
            ModuleLoaded += (s, e) => IsModuleLoaded = true;
            ModuleUnloaded += (s, e) => IsModuleLoaded = false;
        }
        void OnTabControlSelectionChanged(object sender, TabControlSelectionChangedEventArgs e) {
            if(!IsModuleLoaded)
                return;
            MainWindow.CommonRibbon.ShowPageHome = tabControl.SelectedContainer == schedulerTab;
            MainWindow.CommonRibbon.Update();
        }
    }
}
